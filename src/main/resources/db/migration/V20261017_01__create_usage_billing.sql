-- AI 사용량, 요금제 구독, 결제 수단, 결제 기록, 추가 사용량, 사용자 AI 키

CREATE TABLE ai_usage_event (
    usage_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    project_id BIGINT,
    feature VARCHAR(40) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    provider VARCHAR(40) NOT NULL,
    model VARCHAR(120) NOT NULL,
    input_tokens BIGINT NOT NULL DEFAULT 0,
    output_tokens BIGINT NOT NULL DEFAULT 0,
    calls INTEGER NOT NULL DEFAULT 1,
    -- 원 단위 예상 비용(소수 4자리). 사용자 키로 쓴 호출은 0이다. 사용자에게는 보여 주지 않는다.
    cost_krw NUMERIC(14, 4) NOT NULL DEFAULT 0,
    -- 이 중 추가 사용량(크레딧)에서 차감한 몫
    credit_krw NUMERIC(14, 4) NOT NULL DEFAULT 0,
    byok BOOLEAN NOT NULL DEFAULT FALSE,
    -- 한도 계산에 넣는지. 실패한 생성처럼 사용자에게 청구하지 않는 기록은 FALSE.
    counted BOOLEAN NOT NULL DEFAULT TRUE,
    reference VARCHAR(80),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ai_usage_event_member_time_idx ON ai_usage_event(member_id, created_at);

-- 등록한 카드. 빌링키는 암호화해 저장한다. 회원마다 기본 카드 하나로 정기결제·추가 구매를 한다.
CREATE TABLE payment_method (
    payment_method_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    billing_key_encrypted TEXT NOT NULL,
    card_summary VARCHAR(80),
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX payment_method_member_idx ON payment_method(member_id);

CREATE TABLE member_subscription (
    member_id BIGINT PRIMARY KEY,
    plan VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    period_start TIMESTAMP WITH TIME ZONE,
    period_end TIMESTAMP WITH TIME ZONE,
    cancel_at_period_end BOOLEAN NOT NULL DEFAULT FALSE,
    next_billing_at TIMESTAMP WITH TIME ZONE,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    granted_by_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX member_subscription_billing_idx ON member_subscription(status, next_billing_at);

-- 추가 사용량 잔액(원 단위 내부 값). 요금제 한도를 다 쓰면 여기서 차감한다.
CREATE TABLE member_credit (
    member_id BIGINT PRIMARY KEY,
    balance_krw NUMERIC(14, 4) NOT NULL DEFAULT 0,
    -- 추가 사용량을 쓸지(사용자가 켜고 끈다). 꺼져 있으면 잔액이 있어도 한도에서 멈춘다.
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    -- 한 달(사용량 기간)에 추가 사용량으로 쓸 수 있는 최대 금액. 비우면 제한 없음.
    monthly_cap_krw BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE billing_payment (
    billing_payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    payment_id VARCHAR(64) NOT NULL,
    -- SUBSCRIPTION(요금제) 또는 CREDIT(추가 사용량)
    kind VARCHAR(20) NOT NULL,
    plan VARCHAR(20),
    credit_krw NUMERIC(14, 4),
    amount_krw BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    order_name VARCHAR(120) NOT NULL,
    period_start TIMESTAMP WITH TIME ZONE,
    period_end TIMESTAMP WITH TIME ZONE,
    card_summary VARCHAR(80),
    receipt_url TEXT,
    failure_reason VARCHAR(300),
    paid_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_billing_payment_payment_id UNIQUE (payment_id)
);
CREATE INDEX billing_payment_member_idx ON billing_payment(member_id, created_at);

CREATE TABLE llm_credential (
    llm_credential_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    provider VARCHAR(20) NOT NULL,
    base_url VARCHAR(300) NOT NULL,
    model VARCHAR(120) NOT NULL,
    -- AES-GCM으로 암호화한 키. 평문은 저장하지 않고 화면에도 돌려주지 않는다.
    api_key_encrypted TEXT NOT NULL,
    key_hint VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    last_verified_at TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR(300),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX llm_credential_member_idx ON llm_credential(member_id);
