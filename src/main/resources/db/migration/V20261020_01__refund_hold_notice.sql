-- 결제별 환불한 금액. 전액이면 status=CANCELLED, 일부면 PARTIAL_CANCELLED.
ALTER TABLE billing_payment ADD COLUMN refunded_krw BIGINT NOT NULL DEFAULT 0;
ALTER TABLE billing_payment ADD COLUMN refunded_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE billing_payment ADD COLUMN refund_reason VARCHAR(300);

-- 시작했지만 아직 사용량을 기록하지 않은 AI 호출. 동시에 여러 번 불러 한도를 넘기지 않도록
-- 남은 양에서 미리 빼 두고, 기록이 끝나면 지운다. 끝나지 못한 호출은 expires_at이 지나면 무시한다.
CREATE TABLE ai_usage_hold (
    usage_hold_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    feature VARCHAR(40) NOT NULL,
    amount_krw NUMERIC(14, 4) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ai_usage_hold_member_idx ON ai_usage_hold(member_id, expires_at);

-- 같은 알림(결제 예정, 사용량 80%, 비용 경보 등)을 두 번 보내지 않도록 남긴다.
CREATE TABLE billing_notice (
    billing_notice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(40) NOT NULL,
    ref VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT billing_notice_kind_ref_uk UNIQUE (kind, ref)
);
